#!/usr/bin/env python3
"""make_masks_preview.py -- the three sampling patterns of the redone diff-mask study, for inspection only (2026-11-11).

The September diff-mask study (server: /data0/congcong/code/GS/mcgs_diffmask_wt, topics
Results_20260908/T1FLAIR_AF16_{gauss,radial}_v3_jiangyizhou) compared the house vd-Poisson mask with a Gaussian
variable-density random mask and a Cartesian pseudo-radial mask that carried the 24 x 16 ACS block. The user asked on
2026-11-11 for three different rows:

  1 vdpois   the house variable-density Poisson-disc mask at AF 16 -- the existing file of T1FLAIR_AF16_v3_jiangyizhou,
             read here and NOT regenerated (vdPoisMex seeds from time(0); 2966 points, T1 15.19x).
  2 updisc   uniform-density mask from Michael Lustig's ESPIRiT toolbox: the house generator vdPoisMex with pp = 0
             ("polynomial order of variable density (0 = uniform)") instead of the house pp = 1. The 24 x 16 centre
             block is fully sampled and the rest of the plane is sampled at one density everywhere; the points still
             keep the generator's minimum spacing. Generated by gen_mask2_vdpoismex_pp0.m, called from here (user,
             2026-11-11, replacing this script's first version, an i.i.d. uniform random draw in numpy).
  3 radial   conventional radial: straight full-diameter spokes through DC at uniform angles i * 180 / N, nothing else
             (no separate ACS block). Angles are uniform in normalised k-space (the plane is 256 x 176 points over the
             same k-max in both directions), each spoke is a one-point-wide line (one sample per step along its major
             axis), and all spokes have the same length.

Budget: masks 2 and 3 hold exactly 2964 of 45056 points (T1 15.20x), the September study's budget, so the three rows
stay comparable. For the radial mask N is the smallest spoke count that reaches the budget and the few excess points are
removed at the spoke tips (largest normalised radius), leaving every spoke on one common radius.

Also drawn, as an alternative only: the radial mask with the 24 x 16 ACS block added (L1-SPIRiT calibrates its kernel
from the mask's fully sampled centre block; pure spokes leave only a few fully sampled points around DC).

This script writes nothing into Results_20260908. Outputs go to $MCGS_ARTIFACT_DIR: the preview figure, the candidate
masks (.mat, key 'mask', float32 (256, 176)) and a JSON read-out. The radial masks are deterministic (numpy
Generator(seed 0)); mask 2 is not (vdPoisMex seeds from time(0)), its saved file is the record.
"""
import hashlib
import json
import os
import subprocess
from pathlib import Path

import h5py
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import scipy.io as sio

RES = Path("/data0/congcong/code/GS/Results_20260908")
REF_MASK = RES / "T1FLAIR_AF16_v3_jiangyizhou/data/mask_vdpois_256x176_af16.mat"     # READ ONLY
KSP_FLAIR = RES / "T1FLAIR_AF12_v3_jiangyizhou/data/ksp_FLAIR.h5"                    # READ ONLY
OUT = Path(os.environ.get("MCGS_ARTIFACT_DIR", "."))
NY, NZ = 256, 176                               # (ky, kz) phase-encode plane
CY, CZ = 128, 88
N_PLANE = NY * NZ
TARGET = 2964                                   # 45056 / 2964 = 15.20x on T1, the September study's budget
ACS = (24, 16)                                  # ky x kz, the house AF16 mask's fully sampled centre block
SEED = 0
KY, KZ = np.mgrid[0:NY, 0:NZ]
RN = np.sqrt(((KY - CY) / (NY / 2)) ** 2 + ((KZ - CZ) / (NZ / 2)) ** 2)   # normalised radius, 1 at the plane edge


def acs_block():
    m = np.zeros((NY, NZ), dtype=bool)
    m[CY - ACS[0] // 2:CY + ACS[0] // 2, CZ - ACS[1] // 2:CZ + ACS[1] // 2] = True
    return m


def largest_full_rect(m):
    """largest (by area) fully sampled rectangle centred on DC, even extents (ky, kz)"""
    best = (0, 0)
    for hy in range(1, 64):
        if not m[CY - hy:CY + hy, CZ - 1:CZ + 1].all():
            break
        for hz in range(1, 64):
            if not m[CY - hy:CY + hy, CZ - hz:CZ + hz].all():
                break
            if 4 * hy * hz > best[0] * best[1]:
                best = (2 * hy, 2 * hz)
    return best


def flair_shutter():
    with h5py.File(KSP_FLAIR, "r") as f:
        sup = np.any(np.abs(np.array(f["kspace"][0])) > 0, axis=0)
    assert sup.shape == (NY, NZ) and int(sup.sum()) == 34139, (sup.shape, int(sup.sum()))
    return sup


def draw_vdpoismex_pp0():
    """mask 2: vdPoisMex with pp = 0, drawn by the MATLAB script beside this file (compiled mex, not rebuilt)"""
    script = Path(__file__).resolve().with_name("gen_mask2_vdpoismex_pp0.m")
    env = dict(os.environ, MASK2_OUT=str(OUT.resolve()))
    r = subprocess.run(["/usr/local/bin/matlab", "-batch", f"run('{script}')"], env=env, text=True,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    print(r.stdout, flush=True)
    assert r.returncode == 0, "MATLAB failed"
    d = sio.loadmat(OUT / "mask_vdpoismex_pp0_256x176_af16_preview.mat")
    m = d["mask"].astype(bool)
    assert m.shape == (NY, NZ), m.shape
    info = dict(generator="/data0/congcong/code/ESPIRiT/utils/vdPoisMex (mex)",
                call="vdPoisMex(256,176,256,176, accelx, 4, 24, 0, 0)", accelx=float(d["accelx"].squeeze()),
                accely=4, calib=24, ellipse=0, pp=0, draw=int(d["draw"].squeeze()), n_draws=int(d["n_draws"].squeeze()),
                exact_hit=bool(d["exact_hit"].squeeze()), accelx_fit=float(d["accel_star"].squeeze()))
    return m, info


def spokes(n):
    """n full-diameter spokes through DC, uniform angles in normalised k-space, one-point-wide lines"""
    m = np.zeros((NY, NZ), dtype=bool)
    for i in range(n):
        th = i * np.pi / n
        dy, dz = (NY / 2) * np.cos(th), (NZ / 2) * np.sin(th)          # half-spoke in grid units
        steps = int(np.ceil(max(abs(dy), abs(dz))))
        t = np.arange(-steps, steps + 1) / steps                       # one sample per step along the major axis
        ky = np.rint(CY + t * dy).astype(int)
        kz = np.rint(CZ + t * dz).astype(int)
        ok = (ky >= 0) & (ky < NY) & (kz >= 0) & (kz < NZ)
        m[ky[ok], kz[ok]] = True
    return m


def draw_radial(with_acs, seed=SEED):
    rng = np.random.default_rng(seed)
    keep = acs_block() if with_acs else np.zeros((NY, NZ), dtype=bool)
    for n in range(1, 400):
        u = keep | spokes(n)
        if int(u.sum()) >= TARGET:
            break
    else:
        raise RuntimeError("no spoke count reaches the target")
    excess = int(u.sum()) - TARGET
    outside = np.flatnonzero((u & ~keep).reshape(-1))
    r = RN.reshape(-1)[outside]
    order = np.lexsort((rng.random(r.size), -r))                       # spoke tips first, random tie-break
    m = u.copy()
    m.reshape(-1)[outside[order[:excess]]] = False
    assert int(m.sum()) == TARGET
    info = dict(spokes=n, angle_step_deg=180.0 / n, acs_block=bool(with_acs), points_before_trim=int(u.sum()),
                trimmed_at_tips=excess, rn_max_kept=float(RN[m & ~keep].max()),
                points_previous_spoke_count=int((keep | spokes(n - 1)).sum()))
    return m, info


def stats(m, sup):
    n, n_fl = int(m.sum()), int((m & sup).sum())
    flip = m[::-1, ::-1]                                               # conjugate partner of (ky, kz) about DC
    conj = np.zeros_like(m)
    conj[1:, 1:] = flip[:-1, :-1]
    return dict(points=n, T1_AF=N_PLANE / n, FLAIR_points_with_data=n_fl, FLAIR_points_outside_shutter=n - n_fl,
                FLAIR_AF=N_PLANE / n_fl, largest_full_centred_rect_ky_kz=list(largest_full_rect(m)),
                median_rn=float(np.median(RN[m])), conjugate_pair_fraction=float((m & conj).sum() / n))


def profile(m, edges):
    """sampled fraction of the plane in rings of the normalised radius"""
    out = np.full(edges.size - 1, np.nan)
    for i in range(edges.size - 1):
        ring = (RN >= edges[i]) & (RN < edges[i + 1])
        if ring.any():
            out[i] = m[ring].mean()
    return out


def show_mask(ax, m, sup, title):
    ax.imshow(m.T, cmap="gray", origin="lower", interpolation="nearest", vmin=0, vmax=1)
    ax.contour(sup.T.astype(float), levels=[0.5], colors=["#eda100"], linewidths=0.7, linestyles="--")
    ax.set_title(title, fontsize=10.5)
    ax.set_xlabel("ky (256)", fontsize=9)
    ax.set_ylabel("kz (176)", fontsize=9)
    ax.tick_params(labelsize=8)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    sup = flair_shutter()
    ref = sio.loadmat(REF_MASK)["mask"].astype(bool)
    assert ref.shape == (NY, NZ), ref.shape
    updisc, uinfo = draw_vdpoismex_pp0()
    radial, rinfo = draw_radial(with_acs=False)
    radial_acs, rinfo_acs = draw_radial(with_acs=True)

    masks = {"vdpois": ref, "updisc": updisc, "radial": radial, "radial_acs": radial_acs}
    rep = {k: stats(v, sup) for k, v in masks.items()}
    rep["updisc"]["vdpoismex"] = uinfo
    rep["radial"]["radial"] = rinfo
    rep["radial_acs"]["radial"] = rinfo_acs
    rep["vdpois"]["source"] = str(REF_MASK)
    rep["vdpois"]["md5"] = hashlib.md5(open(REF_MASK, "rb").read()).hexdigest()
    rep["updisc"]["md5"] = hashlib.md5(open(OUT / "mask_vdpoismex_pp0_256x176_af16_preview.mat", "rb").read()).hexdigest()
    for k in ("radial", "radial_acs"):
        p = OUT / f"mask_{k}_256x176_af16_preview.mat"
        sio.savemat(p, {"mask": masks[k].astype(np.float32)}, format="5")
        rep[k]["md5"] = hashlib.md5(open(p, "rb").read()).hexdigest()
    rep["_common"] = dict(plane=[NY, NZ], dc=[CY, CZ], target_points=TARGET, acs_block_ky_kz=list(ACS), seed=SEED,
                          flair_shutter_points=int(sup.sum()), status="preview only; nothing registered or reconstructed")
    json.dump(rep, open(OUT / "masks_af16_redo_preview.json", "w"), indent=1)
    for k in masks:
        s = rep[k]
        print(f"[{k}] {s['points']} points, T1 {s['T1_AF']:.2f}x, FLAIR {s['FLAIR_AF']:.2f}x "
              f"({s['FLAIR_points_outside_shutter']} outside the shutter), full centre rect "
              f"{s['largest_full_centred_rect_ky_kz']}, median rn {s['median_rn']:.3f}, "
              f"conjugate pairs {100 * s['conjugate_pair_fraction']:.1f}%"
              + (f", {s['radial']['spokes']} spokes, {s['radial']['trimmed_at_tips']} trimmed, "
                 f"rn max {s['radial']['rn_max_kept']:.3f}" if "radial" in s else ""), flush=True)

    def cap(k):
        s = rep[k]
        return f"{s['points']} points   T1 {s['T1_AF']:.2f}x   FLAIR {s['FLAIR_AF']:.2f}x"

    fig = plt.figure(figsize=(15.5, 8.6), facecolor="#fcfcfb")
    gs = fig.add_gridspec(2, 3, hspace=0.36, wspace=0.2, left=0.05, right=0.985, top=0.875, bottom=0.07)
    show_mask(fig.add_subplot(gs[0, 0]), ref, sup, "1  vd-Poisson disc (house AF16 mask, unchanged)\n" + cap("vdpois"))
    show_mask(fig.add_subplot(gs[0, 1]), updisc, sup,
              "2  uniform density + 24 x 16 ACS (ESPIRiT toolbox vdPoisMex, pp = 0)\n" + cap("updisc"))
    show_mask(fig.add_subplot(gs[0, 2]), radial, sup,
              f"3  conventional radial, {rinfo['spokes']} spokes every {rinfo['angle_step_deg']:.2f} deg, no ACS block\n"
              + cap("radial"))
    show_mask(fig.add_subplot(gs[1, 2]), radial_acs, sup,
              f"alternative to 3: radial + 24 x 16 ACS, {rinfo_acs['spokes']} spokes\n" + cap("radial_acs"))

    ax = fig.add_subplot(gs[1, 0:2])
    ax.set_facecolor("#fcfcfb")
    edges = np.linspace(0.0, 1.4, 29)
    mid = 0.5 * (edges[:-1] + edges[1:])
    series = [("vdpois", "1  vd-Poisson disc", "#2a78d6"), ("updisc", "2  uniform density + ACS (vdPoisMex pp = 0)", "#eb6834"),
              ("radial", "3  conventional radial", "#1baf7a")]
    for k, name, col in series:
        ax.plot(mid, profile(masks[k], edges), color=col, lw=2, marker="o", ms=3.5, label=name)
    ax.set_yscale("log")
    ax.set_ylim(0.008, 1.3)
    ax.set_xlim(0, 1.4)
    ax.axvline(1.0, color="#52514e", lw=0.8, ls=":")
    ax.text(1.005, 0.9, "plane edge on the axes;\nbeyond: corners only", fontsize=8, color="#52514e", va="top")
    ax.set_xlabel("normalised k-space radius rn", fontsize=9)
    ax.set_ylabel("sampled fraction of the ring (log)", fontsize=9)
    ax.set_title("sampling density against radius: 1 falls off steeply, 2 is flat outside the ACS, 3 falls as 1 / radius",
                 fontsize=10.5)
    ax.grid(True, which="major", color="#52514e", alpha=0.15, lw=0.6)
    ax.tick_params(labelsize=8)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    ax.legend(fontsize=9, frameon=False, loc="lower left")

    fig.suptitle("jiangyizhou T1 + FLAIR, nominal AF 16: the three sampling patterns as redrawn on 2026-11-11 "
                 "(preview, nothing reconstructed)\nDashed line: FLAIR's acquired region (vendor shutter); "
                 "samples outside it carry no FLAIR data", fontsize=10, y=0.985)
    fig.savefig(OUT / "masks_af16_redo_preview.png", dpi=200, facecolor=fig.get_facecolor())
    print("wrote", OUT / "masks_af16_redo_preview.png", flush=True)


if __name__ == "__main__":
    main()
